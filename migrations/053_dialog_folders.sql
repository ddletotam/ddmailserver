-- 053: папки диалогов desktop-клиента (табы над списком бесед, как в Telegram).
--
-- Один документ на пользователя. Сервер его не толкует: диалоги считает
-- клиент (и для ящиков, приехавших по IMAP напрямую, сервер их вообще не
-- видит), так что правила папок применяет тоже он. Сервер хранит JSON, проверяет,
-- что это JSON разумного размера, и раздаёт его всем станциям пользователя.
--
-- version — оптимистичная блокировка: запись принимается, только если клиент
-- правил ту версию, что лежит сейчас. Иначе две станции молча затирали бы
-- папки друг друга.
--
-- Идемпотентна.

CREATE TABLE IF NOT EXISTS dialog_folders (
    user_id    BIGINT NOT NULL PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    doc        TEXT   NOT NULL,
    version    BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);
